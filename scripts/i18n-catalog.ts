// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - A synchronous maintainer script over source files.
/**
 * Syncs UI catalogs with the `t`/`tx`/`msg`/`tn` literals in source (`tn` keys on its `other` form).
 * Usage: `check` | `missing <file>` (to translate) | `merge <file>...` (adds, prunes stale, rewrites).
 */
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
// The compiler API; TypeScript 7 no longer exports it.
import ts from "typescript-legacy";

const ROOT = NodePath.resolve(import.meta.dirname, "..");
const SOURCE_DIRS = [
  "apps/web/src",
  "apps/mobile/src",
  "apps/desktop/src",
  "packages/client-runtime/src",
  "packages/shared/src",
];
const CATALOGS = { uk: "packages/client-runtime/src/i18n/locales/uk.ts" } as const;
const GLOSSARY = ".agents/skills/translate-ui/glossary.md";
const PLURAL_CATEGORIES = ["zero", "one", "two", "few", "many", "other"] as const;
const PLACEHOLDER = /\{(\w+)\}/g;

type PluralForms = Partial<Record<(typeof PLURAL_CATEGORIES)[number], string>>;
type Entry = string | PluralForms;
type Catalog = Record<string, Entry>;
interface Message {
  readonly plural: boolean;
  /** The English singular, for plural messages. */
  readonly one?: string;
  readonly files: Set<string>;
}

function sourceFiles(dir: string): string[] {
  const files: string[] = [];
  for (const entry of NodeFS.readdirSync(dir, { withFileTypes: true })) {
    const path = NodePath.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== "node_modules" && entry.name !== "locales")
        files.push(...sourceFiles(path));
    } else if (/\.tsx?$/.test(entry.name) && !/\.(test|spec|bench)\.tsx?$/.test(entry.name)) {
      files.push(path);
    }
  }
  return files;
}

function literalText(node: ts.Node | undefined): string | undefined {
  return node && (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node))
    ? node.text
    : undefined;
}

/** The literal, or each literal branch of `cond ? "A" : "B"`, which the `t` types also accept. */
function literalTexts(node: ts.Node | undefined): string[] {
  if (node && ts.isParenthesizedExpression(node)) return literalTexts(node.expression);
  if (node && ts.isConditionalExpression(node)) {
    return [...literalTexts(node.whenTrue), ...literalTexts(node.whenFalse)];
  }
  const text = literalText(node);
  return text === undefined ? [] : [text];
}

function collectMessages(): Map<string, Message> {
  const messages = new Map<string, Message>();
  const add = (key: string, file: string, plural: boolean, one?: string) => {
    const existing = messages.get(key);
    if (existing) existing.files.add(file);
    else
      messages.set(key, { plural, ...(one === undefined ? {} : { one }), files: new Set([file]) });
  };
  for (const dir of SOURCE_DIRS) {
    for (const path of sourceFiles(NodePath.join(ROOT, dir))) {
      const text = NodeFS.readFileSync(path, "utf8");
      if (!/\b(?:t|tx|tn|msg)\(/.test(text)) continue;
      const file = NodePath.relative(ROOT, path);
      const source = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, false);
      const visit = (node: ts.Node) => {
        if (ts.isCallExpression(node) && ts.isIdentifier(node.expression)) {
          const name = node.expression.text;
          if (name === "t" || name === "tx" || name === "msg") {
            for (const key of literalTexts(node.arguments[0])) add(key, file, false);
          } else if (name === "tn") {
            const one = literalText(node.arguments[1]);
            const other = literalText(node.arguments[2]);
            if (one !== undefined && other !== undefined) add(other, file, true, one);
          }
        }
        ts.forEachChild(node, visit);
      };
      visit(source);
    }
  }
  return messages;
}

function catalogPath(language: keyof typeof CATALOGS) {
  return NodePath.join(ROOT, CATALOGS[language]);
}

function readCatalog(language: keyof typeof CATALOGS): Catalog {
  const text = NodeFS.readFileSync(catalogPath(language), "utf8");
  const match = text.match(/const catalog: MessageCatalog = (\{[\s\S]*\});\n/);
  if (!match?.[1]) throw new Error(`Could not find the catalog object in ${CATALOGS[language]}.`);
  return Function(`"use strict"; return (${match[1]});`)() as Catalog;
}

function writeCatalog(language: keyof typeof CATALOGS, catalog: Catalog) {
  const sorted = Object.fromEntries(
    Object.keys(catalog)
      .toSorted((a, b) => a.localeCompare(b, "en"))
      .map((key) => [key, catalog[key]]),
  );
  NodeFS.writeFileSync(
    catalogPath(language),
    `import type { MessageCatalog } from "@t3tools/shared/i18n";\n\n` +
      `// Generated by \`node scripts/i18n-catalog.ts\`; keys are the English messages.\n` +
      `const catalog: MessageCatalog = ${JSON.stringify(sorted, null, 2)};\n\nexport default catalog;\n`,
  );
}

function placeholders(text: string) {
  return new Set([...text.matchAll(PLACEHOLDER)].map((match) => match[1] ?? ""));
}

/**
 * Problems with one entry: a wrong shape, or placeholders the source does not have or that a
 * translation drops. Plural forms may use either English form's placeholders and may omit
 * {count}, as in Ukrainian "одна гілка".
 */
function entryProblems(key: string, message: Message, entry: Entry): string[] {
  const problems: string[] = [];
  if (message.plural && typeof entry === "string") problems.push("plural message needs forms");
  if (!message.plural && typeof entry !== "string") problems.push("message is not plural");
  const other = placeholders(key);
  const one = placeholders(message.one ?? key);
  const allowed = new Set([...other, ...one]);
  const required = [...other].filter(
    (name) => one.has(name) && !(message.plural && name === "count"),
  );
  const texts =
    typeof entry === "string"
      ? [entry]
      : Object.values(entry).filter((value) => value !== undefined);
  for (const text of texts) {
    const found = placeholders(text);
    const extra = [...found].filter((name) => !allowed.has(name));
    const dropped = required.filter((name) => !found.has(name));
    if (extra.length > 0 || dropped.length > 0) {
      problems.push(`placeholders differ from the source in ${JSON.stringify(text)}`);
    }
  }
  return problems;
}

const LETTER_RUN = /\p{L}{2,}/gu;
// Paths, URLs, and kebab or dotted identifiers are code, which stays as written.
const CODE_TOKEN = /\/|^[\p{Ll}\d]+(?:[-_.][\p{Ll}\d]+)+$/u;

/** Words of the glossary's "Keep in English" bullets, lowercased. */
function keptEnglishWords(): Set<string> {
  const glossary = NodeFS.readFileSync(NodePath.join(ROOT, GLOSSARY), "utf8");
  const section = glossary.split("## Keep in English")[1]?.split("\n## ")[0] ?? "";
  const items = section
    .split("\n- ")
    .slice(1)
    .map((item) => item.slice(item.indexOf(":") + 1));
  return new Set(items.join(" ").toLowerCase().match(LETTER_RUN) ?? []);
}

/** Words of an untouched English message that the glossary doesn't keep in English. */
function untranslatedWords(key: string, kept: Set<string>): string[] {
  return key
    .replace(PLACEHOLDER, " ")
    .split(/\s+/)
    .filter((token) => !CODE_TOKEN.test(token))
    .flatMap((token) => token.match(LETTER_RUN) ?? [])
    .filter((word) => !kept.has(word.toLowerCase()));
}

function check() {
  const kept = keptEnglishWords();
  const messages = collectMessages();
  let failed = false;
  for (const language of Object.keys(CATALOGS) as Array<keyof typeof CATALOGS>) {
    const catalog = readCatalog(language);
    const missing = [...messages.keys()].filter((key) => !Object.hasOwn(catalog, key));
    const stale = Object.keys(catalog).filter((key) => !messages.has(key));
    const categories = new Intl.PluralRules(language).resolvedOptions().pluralCategories;
    const broken = [...messages].flatMap(([key, message]) => {
      if (!Object.hasOwn(catalog, key)) return [];
      const entry = catalog[key]!;
      const problems = entryProblems(key, message, entry);
      if (typeof entry !== "string") {
        const absent = categories.filter((category) => entry[category] === undefined);
        if (absent.length > 0) problems.push(`plural forms missing: ${absent.join(", ")}`);
      } else if (entry === key) {
        const words = untranslatedWords(key, kept);
        if (words.length > 0) {
          problems.push(
            `identical to English; translate it, or add ${words.join(", ")} to ${GLOSSARY}`,
          );
        }
      }
      return problems.map((problem) => `${JSON.stringify(key)}: ${problem}`);
    });
    for (const [label, list] of [
      [
        "missing",
        missing.map((key) => `${JSON.stringify(key)} (${[...messages.get(key)!.files][0]})`),
      ],
      ["stale", stale.map((key) => JSON.stringify(key))],
      ["broken", broken],
    ] as const) {
      if (list.length === 0) continue;
      failed = true;
      console.error(`${language}: ${list.length} ${label}`);
      for (const line of list.slice(0, 50)) console.error(`  ${line}`);
      if (list.length > 50) console.error(`  ...and ${list.length - 50} more`);
    }
    console.log(
      `${language}: ${messages.size} messages, ${Object.keys(catalog).length} translated`,
    );
  }
  if (failed) {
    console.error("To fix, follow .agents/skills/translate-ui/SKILL.md.");
    process.exitCode = 1;
  }
}

function writeMissing(outPath: string) {
  const messages = collectMessages();
  const catalog = readCatalog("uk");
  const missing = [...messages]
    .filter(([key]) => !Object.hasOwn(catalog, key))
    .map(([key, message]) => ({
      message: key,
      ...(message.plural ? { plural: true, one: message.one } : {}),
      file: [...message.files][0],
    }));
  NodeFS.writeFileSync(outPath, `${JSON.stringify(missing, null, 2)}\n`);
  console.log(`${missing.length} untranslated messages written to ${outPath}`);
}

function merge(inputs: readonly string[]) {
  const messages = collectMessages();
  const catalog = readCatalog("uk");
  for (const input of inputs) {
    const translations = JSON.parse(NodeFS.readFileSync(input, "utf8")) as Catalog;
    for (const [key, entry] of Object.entries(translations)) {
      const message = messages.get(key);
      if (!message) continue;
      const problems = entryProblems(key, message, entry);
      if (problems.length > 0) {
        console.error(`Skipped ${JSON.stringify(key)}: ${problems.join("; ")}`);
        continue;
      }
      catalog[key] = entry;
    }
  }
  for (const key of Object.keys(catalog)) if (!messages.has(key)) delete catalog[key];
  writeCatalog("uk", catalog);
  console.log(`uk: ${Object.keys(catalog).length} of ${messages.size} messages translated`);
}

const [command, ...args] = process.argv.slice(2);
if (command === "check") check();
else if (command === "missing" && args[0]) writeMissing(args[0]);
else if (command === "merge" && args.length > 0) merge(args);
else {
  console.error("Usage: node scripts/i18n-catalog.ts check | missing <file> | merge <file>...");
  process.exitCode = 1;
}
